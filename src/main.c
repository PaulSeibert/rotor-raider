// The title camera's height, nudged (down, 8 px at a time) so that over the
// whole pan no island band starts and the ring doesn't wrap on the logo's
// lines: then its copper block stays put (written once a buffer)
static void titleCamFit(void) {
	tGame *g = &s_sGame;
	WORD wMaxY = (WORD)(g->map.uwH * TILE - PLAY_H);
	WORD wCol0 = (WORD)((((g->titleX0 - 1) >> 4) * 2) / SCROLL_BW);
	WORD wCol1 = (WORD)((((g->titleX0 + 600 - 1) >> 4) * 2) / SCROLL_BW) + 1;
	for(UWORD k = 0; k < SCROLL_ROWS / 8 + 1; ++k) {
		WORD y = (WORD)(g->titleY0 + k * 8);
		if(y > wMaxY) y = (WORD)(wMaxY - (WORD)(k * 8 - (wMaxY - g->titleY0)));
		if(y < 0) break;
		UBYTE isOk = 1;
		for(UBYTE b = 1; b < s_sTheatre.ubBands; ++b) {
			WORD wLine = (WORD)(s_sTheatre.pBands[b].ubRow * TILE - y);
			if(wLine >= 0 && wLine <= LOGO_Y + LOGO_H + 2) isOk = 0;
		}
		for(WORD d = wCol0; d <= wCol1 && isOk; ++d) {
			WORD r = (WORD)(y + d);
			while(r >= SCROLL_ROWS) r = (WORD)(r - SCROLL_ROWS);
			if(SCROLL_ROWS - r <= LOGO_Y + LOGO_H + 2) isOk = 0;
		}
		if(isOk) {
			g->titleY0 = y;
			return;
		}
	}
}

// ----------------------------------------------------------- blit queue ---
// Each picture: erase what this buffer showed last time, then draw the
// objects back to front. The CPU feeds the blits to the blitter while it
// runs the game (agk/blitq.h, as in Rotor Rescue).

#define TPL_MAX 128
static void msgCoverBegin(UBYTE ubBfr);
static void msgCover(UBYTE ubBfr, WORD x, WORD y, UWORD uwW, UBYTE ubH);
static tAgkBlitArea s_pErase[2][DRAW_MAX];
static UBYTE s_pErased[2];
static tBitMap *s_pBobBm[BOB_TYPES], *s_pBobMask[BOB_TYPES];
static UBYTE s_pTplFirst[BOB_TYPES];
static tAgkBlit s_pTpl[TPL_MAX][2];
static UWORD s_pFbRowOffs[FB_H];
static tDraw s_pDraw[DRAW_MAX];

static void bobAdd(UBYTE ubBob, tBitMap *pBm, tBitMap *pMask, UWORD uwW, UBYTE ubH, UBYTE ubFrames) {
	s_pBobBm[ubBob] = pBm;
	s_pBobMask[ubBob] = pMask;
	if(uwW != g_pBobW[ubBob] || ubH != g_pBobH[ubBob] || ubFrames != g_pBobFrames[ubBob]) {
		agkPrint("AGK ERR logic.c's BOB sizes don't match the art\n");
	}
}

// The BOBs from the floppy (disk/bobs.bin): each one's image and mask, built
// into chip RAM the way agk's art.c does (a row: 3 planes' words, the mask's)
static void bobsCreate(void) {
	UBYTE *pBlob = memAllocFast(BOBS_BYTES);
	if(agkLoadFile("bobs.bin.pk", pBlob, BOBS_BYTES) != BOBS_BYTES) agkPrint("AGK ERR can't load bobs.bin\n");
	agkPerfSkip();
	for(UBYTE b = 0; b < BOB_TYPES; ++b) {
		const tBobFile *pF = &g_pBobFile[b];
		UWORD uwRows = (UWORD)(pF->uwH * pF->uwFrames), uwWords = (UWORD)(pF->uwW >> 4);
		tBitMap *pBm = bitmapCreate(pF->uwW, uwRows, 3, BMF_CLEAR | BMF_INTERLEAVED);
		tBitMap *pMask = bitmapCreate(pF->uwW, uwRows, 3, BMF_CLEAR | BMF_INTERLEAVED);
		const UWORD *pSrc = (const UWORD *)(pBlob + pF->ulOffs);
		for(UWORD y = 0; y < uwRows; ++y) {
			for(UBYTE p = 0; p < 3; ++p) {
				UWORD *pDst = (UWORD *)(pBm->Planes[p] + (ULONG)y * pBm->BytesPerRow);
				for(UWORD w = 0; w < uwWords; ++w) pDst[w] = *pSrc++;
			}
			for(UBYTE p = 0; p < 3; ++p) {
				UWORD *pDst = (UWORD *)(pMask->Planes[p] + (ULONG)y * pMask->BytesPerRow);
				for(UWORD w = 0; w < uwWords; ++w) pDst[w] = pSrc[w];
			}
			pSrc += uwWords;
		}
		bobAdd(b, pBm, pMask, pF->uwW, (UBYTE)pF->uwH, (UBYTE)pF->uwFrames);
	}
	memFree(pBlob, BOBS_BYTES);
	UBYTE t = 0;
	for(UBYTE b = 0; b < BOB_TYPES; ++b) {
		s_pTplFirst[b] = t;
		for(UBYTE f = 0; f < g_pBobFrames[b] && t < TPL_MAX; ++f, ++t) {
			agkBlitBob(s_pTpl[t], s_pBobBm[b], s_pBobMask[b], g_pBobW[b], g_pBobH[b], f, FB_PLANE_BYTES);
		}
	}
	if(t >= TPL_MAX) agkPrint("AGK ERR too many BOB frames: raise TPL_MAX\n");
	for(UWORD y = 0; y < FB_H; ++y) s_pFbRowOffs[y] = (UWORD)(y * FB_ROW_BYTES);
}

__attribute__((noinline)) static void erasesQueue(UBYTE ubBfr) {
	agkBlitqReset();
	const tAgkBlitArea *pDrawn = s_pErase[ubBfr];
	for(UBYTE i = s_pErased[ubBfr]; i--; ++pDrawn) {
		agkBlitClear(agkBlitqSlot(), pDrawn);
		agkBlitqPush();
	}
}

// The title's logo: blitted once into each buffer while the title shows (no
// erase and redraw each picture: a 160 x 146 cookie-cut is ~80 raster lines
// of the blitter), cleared once when it goes. Nothing crosses it there: on the
// title, objectsQueue leaves out what would.
static tAgkBlitArea s_pLogoArea[2];

static void logoQueue(UBYTE ubBfr) {
	UBYTE isTitle = s_sGame.state == GS_TITLE;
	if(isTitle == s_pLogoShown[ubBfr]) return;
	s_pLogoShown[ubBfr] = isTitle;
	s_pLogoIn[ubBfr] = 0;
	if(!isTitle) {
		agkBlitClear(agkBlitqSlot(), &s_pLogoArea[ubBfr]);
		agkBlitqPush();
		return;
	}
	tAgkBlit *pB = agkBlitqSlot();
	UWORD uwX = (UWORD)(FB_X0 + (SCREEN_W - g_pBobW[BOB_LOGO]) / 2);
	agkBlitPlace(pB, s_pTpl[s_pTplFirst[BOB_LOGO]], g_pBobW[BOB_LOGO], s_pFb[ubBfr]->Planes[0] + s_pFbRowOffs[LOGO_Y], uwX);
	agkBlitArea(&s_pLogoArea[ubBfr], pB);
	agkBlitqPush();
}

__attribute__((noinline)) static void objectsQueue(UBYTE ubBfr) {
	logoQueue(ubBfr);
	tBitMap *pFb = s_pFb[ubBfr];
	UBYTE n = logicDraw(&s_sGame, s_pDraw);
	if(s_sGame.state == GS_TITLE) {
		// (the logo isn't redrawn: nothing may cross it, BOB or gun sprite)
		tDraw *pTo = s_pDraw;
		const tDraw *pFrom = s_pDraw;
		UBYTE k = 0;
		for(UBYTE i = n; i--; ++pFrom) if(pFrom->y >= LOGO_Y + LOGO_H) { *pTo++ = *pFrom; ++k; }
		n = k;
	}
	gunsUpdate(ubBfr, s_pDraw, n);
	tAgkBlitArea *pErase = s_pErase[ubBfr];
	msgCoverBegin(ubBfr);
	UBYTE ubDrawn = 0;
	const tDraw *pD = s_pDraw;
	for(UBYTE i = n; i--; ++pD) {
		UBYTE b = pD->bob;
		if(b == BOB_TYPES) continue;          // a gun on a sprite
		WORD x = pD->x + FB_X0, y = pD->y;
		// the buffer's margins hold anything partly off the sides; the top and
		// bottom clip by skipping (a BOB is rarely half off there for long)
		if(x < 0 || y < 0 || x + g_pBobW[b] + 16 > FB_W || y + g_pBobH[b] > FB_H) continue;
		tAgkBlit *pB = agkBlitqSlot();
		agkBlitPlace(pB, s_pTpl[s_pTplFirst[b] + pD->frame], g_pBobW[b], pFb->Planes[0] + s_pFbRowOffs[y], (UWORD)x);
		agkBlitArea(pErase++, pB);
		agkBlitqPush();
		++ubDrawn;
		msgCover(ubBfr, x, y, g_pBobW[b], g_pBobH[b]);
	}
	s_pErased[ubBfr] = ubDrawn;
}

// ------------------------------------------------------------------ rotor ---
// A looped chop (two blade passes of filtered noise) made at startup; the
// period follows the airspeed, the volume the state (as in Rotor Rescue).
//
// Paula's channels (1.4; the README's "Sound" has the whole policy):
//   0 (left)  the rotor while it has the channel, else music
//   1 (right) music; effects on the right of the screen (or the middle)
//   2 (right) music
//   3 (left)  music; effects on the left of the screen (or the middle)
// Before 1.4 the rotor kept channel 2 all game, so the music in the air
// (Songerson's dog70, 1 MB chip) lost its voice 2: the analog string pad, its
// loudest voice, sounding 86% of the song. Now the rotor borrows channel 0,
// which dog70 leaves silent for its first 8 positions (512 rows, 61 s; then it
// loops positions 8-13 with all four voices: sound/tools/mod_voices.py). So the
// rotor loops on channel 0 whenever there's no music in the air (a 512 KB
// A500, or M), and for dog70's first 59 s, then fades out and hands channel 0
// back. From then on it's a short fading chop on an effect channel at take-off
// and landing, and the song keeps all four voices.

#define ROTOR_CHANNEL 0
#define ROTOR_SAMPLES 1200
#define DOG70_VOICE0_FREE 2950  // VBLs from dog70's start: its voice 0 comes in at 3072 ticks (~3067 VBLs)
#define ROTOR_FADE 64           // VBLs fading out before channel 0 goes back to the music
#define BURST_SAMPLES 8000      // the take-off/landing chop: 0.68 s at period 300 (1 MB chip only)
static BYTE *s_pRotorWave;      // chip RAM
static BYTE *s_pBurstWave;      // chip RAM (with dog70 only)
static tPtplayerSfx s_pBurst[2];   // take-off (higher), landing
static UBYTE s_isRotorOwner;    // channel 0 is the rotor's: ptplayer leaves it alone
static UBYTE s_isMusicOn = 1, s_ubSong = 0xFF;
static ULONG s_ulSongStart;     // timerGet() when s_ubSong started

static void rotorCreate(UBYTE isBurst) {
	s_pRotorWave = memAllocChip(ROTOR_SAMPLES);
	UWORD uwLfsr = 0x1D2B;
	WORD wLow = 0, wLow2 = 0;
	for(UWORD i = 0; i < ROTOR_SAMPLES; ++i) {
		UWORD lsb = uwLfsr & 1;
		uwLfsr >>= 1;
		if(lsb) uwLfsr ^= 0xB400;
		WORD wNoise = (WORD)((uwLfsr & 0xFF) - 128);
		wLow = (WORD)(wLow + ((wNoise - wLow) >> 2));
		wLow2 = (WORD)(wLow2 + ((wLow - wLow2) >> 2));
		UWORD uwPhase = i < ROTOR_SAMPLES / 2 ? i : (UWORD)(i - ROTOR_SAMPLES / 2);
		WORD wEnv = uwPhase < 40 ? (WORD)(uwPhase * 3) : (WORD)(120 - ((uwPhase - 40) >> 2));
		if(wEnv < 8) wEnv = 8;
		WORD v = (WORD)((wLow2 * wEnv) >> 5);
		s_pRotorWave[i] = (BYTE)(v > 127 ? 127 : v < -128 ? -128 : v);
	}
	if(isBurst) {
		// the chop fading away over 0.68 s (it starts at full: the gunship
		// lifting off or setting down, then the music takes over)
		s_pBurstWave = memAllocChip(BURST_SAMPLES);
		UWORD j = 0;
		for(UWORD i = 0; i < BURST_SAMPLES; ++i) {
			WORD wEnv = (WORD)(64 - (WORD)(mulw((WORD)i, 64) / BURST_SAMPLES));
			s_pBurstWave[i] = (BYTE)(mulw(s_pRotorWave[j], wEnv) >> 6);
			if(++j == ROTOR_SAMPLES) j = 0;
		}
		s_pBurstWave[0] = s_pBurstWave[1] = 0;
		for(UBYTE k = 0; k < 2; ++k) {
			s_pBurst[k].pData = (UWORD *)s_pBurstWave;
			s_pBurst[k].uwWordLength = BURST_SAMPLES / 2;
			s_pBurst[k].uwPeriod = k ? 300 : 260;
		}
	}
}

// Channel 0 to the rotor (ptplayer leaves it), or back to the music
static void rotorOwn(UBYTE isOwn) {
	if(isOwn == s_isRotorOwner) return;
	s_isRotorOwner = isOwn;
	volatile struct AudChannel *pAud = &g_pCustom->aud[ROTOR_CHANNEL];
	pAud->ac_vol = 0;
	g_pCustom->dmacon = DMAF_AUD0 << ROTOR_CHANNEL;
	if(isOwn) {
		ptplayerSetChannelsForPlayer(0xF & ~(1 << ROTOR_CHANNEL));
		pAud->ac_ptr = (UWORD *)s_pRotorWave;
		pAud->ac_len = ROTOR_SAMPLES / 2;
		pAud->ac_per = 300;
		g_pCustom->dmacon = DMAF_SETCLR | (DMAF_AUD0 << ROTOR_CHANNEL);
		agkPrint("AGK rotor on channel 0\n");
	}
	else {
		ptplayerSetChannelsForPlayer(0xF);
		agkPrint("AGK channel 0 back to the music\n");
	}
}

static UBYTE s_isPaused;

__attribute__((noinline)) static void rotorUpdate(void) {
	const tGame *g = &s_sGame;
	const tChopper *c = &g->chop;
	UBYTE isOwn = 0, ubFade = ROTOR_FADE;
	if(g->state == GS_PLAY || g->state == GS_LOST) {
		if(s_ubSong != SOUND_MUSIC_DOG70) isOwn = 1;   // no music in the air
		else {
			ULONG ulT = timerGet() - s_ulSongStart;
			if(ulT < DOG70_VOICE0_FREE) {
				isOwn = 1;
				if(ulT + ROTOR_FADE > DOG70_VOICE0_FREE) ubFade = (UBYTE)(DOG70_VOICE0_FREE - ulT);
			}
		}
	}
	rotorOwn(isOwn);
	if(!isOwn) return;
	UBYTE ubVol = 0;
	UWORD uwPer = 300;
	if(!(c->crashed && !c->alt)) {
		WORD wSx = c->vx < 0 ? (WORD)-c->vx : c->vx, wSy = c->vy < 0 ? (WORD)-c->vy : c->vy;
		WORD wSpeed = wSx > wSy ? wSx : wSy;
		uwPer = (UWORD)(300 - wSpeed - (c->landed ? 0 : 24) + (c->crashed ? 60 : 0));
		ubVol = c->landed ? 16 : 30;
		ubVol = (UBYTE)(mulw(ubVol, ubFade) >> 6);
	}
	if(s_isPaused) ubVol = 0;
	volatile struct AudChannel *pAud = &g_pCustom->aud[ROTOR_CHANNEL];
	pAud->ac_per = uwPer;
	pAud->ac_vol = ubVol;
}

static void rotorDestroy(void) {
	rotorOwn(0);
	memFree(s_pRotorWave, ROTOR_SAMPLES);
	if(s_pBurstWave) memFree(s_pBurstWave, BURST_SAMPLES);
}

// ---------------------------------------------------------------- sound ---

static UBYTE s_ubModules;          // Songerson's modules in chip RAM (0 on a 512 KB-chip A500)

static void musicFor(UBYTE ubState) {
	UBYTE ubSong = 0xFF;
	// Songerson's modules where they're in chip RAM (loaded at boot if it had
	// room), else the game's own small songs: the title's theme, quiet in the air
	if(ubState == GS_TITLE) ubSong = soundMusicLoaded(SOUND_MUSIC_DOG68) ? SOUND_MUSIC_DOG68 : SOUND_MUSIC_THEME;
	else if(ubState == GS_PLAY || ubState == GS_LOST) ubSong = soundMusicLoaded(SOUND_MUSIC_DOG70) ? SOUND_MUSIC_DOG70 : 0xFF;
	else if(ubState == GS_CLEAR || ubState == GS_VICTORY) ubSong = SOUND_MUSIC_FANFARE;
	else if(ubState == GS_OVER) ubSong = SOUND_MUSIC_GAMEOVER;
	if(!s_isMusicOn) ubSong = 0xFF;
	if(ubSong == s_ubSong) return;
	s_ubSong = ubSong;
	if(ubSong == 0xFF) soundMusicStop();
	else soundMusicStart(ubSong);
	s_ulSongStart = timerGet();
}

// An effect on the side of the screen it happens on: left on channel 3,
// right on 1 (Paula's stereo), near the middle on either. soundPlay picks
// the channel itself, among those ptplayer's music mask leaves it: so for one
// effect the mask leaves only that side's channel. (sound.toml sfx_channels =
// [1, 3]: mask 0x5 otherwise.)
#define SFX_MASK 0x5
static UBYTE s_ubPanLeft, s_ubPanRight;   // effects played on each side (agkState "pan")

static void sfxAt(UBYTE ubSfx, ULONG ulEv) {
	UBYTE ubCh = logicSfxChannel(&s_sGame, ulEv);
	if(ubCh == SFX_EITHER) {
		soundPlay(ubSfx);
		return;
	}
	if(ubCh == SFX_LEFT) ++s_ubPanLeft;
	else ++s_ubPanRight;
	ptplayerSetMusicChannelMask((UBYTE)(0xF & ~(1 << ubCh)));
	soundPlay(ubSfx);
	ptplayerSetMusicChannelMask(SFX_MASK);
}

__attribute__((noinline)) static void playSounds(UBYTE ubStateBefore) {
	const tGame *g = &s_sGame;
	ULONG e = g->events;
	if(g->state != ubStateBefore) {
		musicFor(g->state);
		if(g->state == GS_TITLE) titleCamFit();
		if(ubStateBefore == GS_TITLE && g->state == GS_PLAY) soundPlay(SOUND_SFX_START);
	}
	if(e & EV_CRASH) sfxAt(SOUND_SFX_CRASH, EV_CRASH);
	else if(e & EV_CRUISER_SUNK) sfxAt(SOUND_SFX_FACTORY, EV_CRUISER_SUNK);
	else if(e & EV_FACTORY) sfxAt(SOUND_SFX_FACTORY, EV_FACTORY);
	else if(e & (EV_BIGBOOM | EV_SUNK)) sfxAt(SOUND_SFX_BIGBOOM, e & EV_BIGBOOM ? EV_BIGBOOM : EV_SUNK);
	else if(e & EV_BOOM) sfxAt(SOUND_SFX_BOOM, EV_BOOM);
	if(e & (EV_CRUISER | EV_CRUISER_UP)) soundPlay(SOUND_SFX_KLAXON);   // (an alarm: from anywhere)
	if(e & EV_HIT) sfxAt(SOUND_SFX_HIT, EV_HIT);
	if(e & EV_MISSILE) sfxAt(SOUND_SFX_MISSILE, EV_MISSILE);
	else if(e & EV_FLAK) sfxAt(SOUND_SFX_FLAK, EV_FLAK);
	if(e & EV_CANNON) sfxAt(SOUND_SFX_CANNON, EV_CANNON);
	if(e & EV_BOMB) sfxAt(SOUND_SFX_BOMB, EV_BOMB);
	if(e & EV_LANDED) sfxAt(SOUND_SFX_LAND, EV_LANDED);
	// the music has channel 0: the rotor is a short burst on an effect channel
	if((e & (EV_TAKEOFF | EV_LANDED)) && !s_isRotorOwner && s_pBurstWave && g->state == GS_PLAY) {
		ptplayerSfxPlay(&s_pBurst[e & EV_TAKEOFF ? 0 : 1], g->chop.x - g->camX < SCREEN_W / 2 ? SFX_LEFT : SFX_RIGHT, 40, 2);
		agkPrint("AGK rotor burst\n");
	}
}

