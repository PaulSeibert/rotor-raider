// ---------------------------------------------------------------- gunship ---
// Two sets of the gunship's sprite bitmaps, one per copper buffer (as in
// Rotor Rescue): the back set gets the position (its control words) and the
// back copper list points channels 0-3 at it. No copying a frame: 17 KB of
// chip RAM saves ~25 raster lines a picture.

static tBitMap *s_pChopFrames[2][ART_CHOPPER_FRAMES][ART_CHOPPER_PARTS];
static tBitMap *s_pChopShown[2][ART_CHOPPER_PARTS];     // what each buffer's list points at

static void chopperCreate(void) {
	for(UBYTE b = 0; b < 2; ++b) {
		for(UBYTE f = 0; f < ART_CHOPPER_FRAMES; ++f)
			for(UBYTE p = 0; p < ART_CHOPPER_PARTS; ++p) s_pChopFrames[b][f][p] = artChopperCreate(f, p);
		for(UBYTE p = 0; p < ART_CHOPPER_PARTS; ++p) s_pChopShown[b][p] = s_pChopFrames[b][0][p];
	}
}

__attribute__((noinline)) static void chopperUpdate(UBYTE ubBfr) {
	const tGame *g = &s_sGame;
	UBYTE ubFrame = logicChopperFrame(g);
	WORD wX = (WORD)(g->chop.x - g->camX - 16), wY = (WORD)(g->chop.y - g->camY - 16);
	if(wY < -32 || wY > PLAY_H - 8 || g->state == GS_TITLE || (g->chop.crashed && !g->chop.alt)) wY = -64;
	UWORD uwVStart = (UWORD)(s_pView->ubPosY + wY), uwVStop = (UWORD)(uwVStart + ART_CHOPPER_H);
	for(UBYTE p = 0; p < ART_CHOPPER_PARTS; ++p) {
		tBitMap *pBm = s_pChopFrames[ubBfr][ubFrame][p];
		s_pChopShown[ubBfr][p] = pBm;
		UWORD uwHStart = (UWORD)(s_pView->ubPosX - 1 + wX + (p >> 1) * 16);
		UWORD *pHead = (UWORD *)pBm->Planes[0];
		pHead[0] = (UWORD)((uwVStart << 8) | ((uwHStart >> 1) & 0xFF));
		pHead[1] = (UWORD)((uwVStop << 8) | ((p & 1) << 7) | (((uwVStart >> 8) & 1) << 2) |
			(((uwVStop >> 8) & 1) << 1) | (uwHStart & 1));
	}
}

// ------------------------------------------------------------ gun sprites ---
// The turrets' AA guns ride hardware sprites 4-5: an attached pair (15
// colours) reused down the screen (a gun's control words follow the one
// above it in the list), so neither the blitter nor the CPU draws them.
// A gun the pair has no room for on its lines goes to the blitter.
// Not the 6/7 pair: DDFSTRT $30 (fine scroll) takes sprite 7's DMA, so a gun
// there showed only sprite 6's 3-colour half - pale grey (found 2026-11-11). Each
// copper buffer has its own lists; a slot's image is copied in only when
// its frame changes.

#define GUN_CHANNEL 4
#define GUN_SLOTS 6                   // guns a pair shows, top to bottom
#define GUN_SLOT_WORDS 34             // control words, then 16 rows of 2
#define GUN_LIST_WORDS (GUN_SLOTS * GUN_SLOT_WORDS + 2)
#define GUN_SORT_MAX 16
#define GUN_COPIES 3                  // guns whose image changes, at most, a picture
static UWORD *s_pGunList[2][4];       // chip RAM, per copper buffer and channel
static UBYTE s_pGunCached[2][2][GUN_SLOTS];   // the frame each pair's slot holds (0xFF: none)

static void gunsCreate(void) {
	for(UBYTE b = 0; b < 2; ++b) {
		for(UBYTE c = 0; c < 4; ++c) {
			s_pGunList[b][c] = memAllocChipClear(GUN_LIST_WORDS * 2);
			for(UBYTE s = 0; s < GUN_SLOTS; ++s) s_pGunCached[b][c >> 1][s] = 0xFF;
		}
	}
}

static void gunsDestroy(void) {
	for(UBYTE b = 0; b < 2; ++b)
		for(UBYTE c = 0; c < 4; ++c) memFree(s_pGunList[b][c], GUN_LIST_WORDS * 2);
}

// The draw list starts with the guns (logicDraw puts them first): show
// those that fit on the sprites, and mark them so the blitter skips them
#define GUN_IMG_BYTES 64                      // a sprite's 16 rows: copied as one

__attribute__((noinline)) static void gunsUpdate(UBYTE ubBfr, tDraw *pDraw, UBYTE n) {
	// in order down the screen: keys (y + 32) << 5 | index, insertion-sorted
	UWORD pKey[GUN_SORT_MAX];
	UBYTE ubGuns = 0;
	for(UBYTE i = 0; i < n && pDraw[i].bob == BOB_GUN && ubGuns < GUN_SORT_MAX; ++i) {
		UWORD uwK = (UWORD)(((pDraw[i].y + 32) << 5) | i);
		UBYTE j = ubGuns++;
		while(j && pKey[j - 1] > uwK) {
			pKey[j] = pKey[j - 1];
			--j;
		}
		pKey[j] = uwK;
	}
	UBYTE pSlots[2] = {0, 0};
	WORD pNextY[2] = {-32, -32};
	UWORD uwTop = s_pView->ubPosY, uwLeft = (UWORD)(s_pView->ubPosX - 1);
	UBYTE ubCopies = GUN_COPIES;
	for(UBYTE k = 0; k < ubGuns; ++k) {
		tDraw *pD = &pDraw[pKey[k] & 31];
		WORD y = pD->y;
		UBYTE p;
		if(y >= pNextY[0] && pSlots[0] < GUN_SLOTS) p = 0;
		else continue;                        // no room on its lines: the blitter's
		UBYTE s = pSlots[p]++;
		pNextY[p] = (WORD)(y + 17);           // a line between one and the next
		UBYTE ubRows = (UBYTE)(y + 16 > PLAY_H ? PLAY_H - y : 16);   // not into the HUD
		UWORD uwVStart = (UWORD)(uwTop + y), uwVStop = (UWORD)(uwVStart + ubRows);
		UWORD uwH = (UWORD)(uwLeft + pD->x);
		UWORD uwPos = (UWORD)((uwVStart << 8) | ((uwH >> 1) & 0xFF));
		UWORD uwCtl = (UWORD)((uwVStop << 8) | (((uwVStart >> 8) & 1) << 2) | (((uwVStop >> 8) & 1) << 1) | (uwH & 1));
		UBYTE ubFrame = pD->frame;
		UWORD uwOffs = (UWORD)(s * GUN_SLOT_WORDS);
		UWORD *pE = s_pGunList[ubBfr][p * 2] + uwOffs, *pO = s_pGunList[ubBfr][p * 2 + 1] + uwOffs;
		pE[0] = pO[0] = uwPos;
		pE[1] = uwCtl;
		pO[1] = (UWORD)(uwCtl | 0x80);        // the odd one attached
		UBYTE *pCached = &s_pGunCached[ubBfr][p][s];
		if(ubRows < 16) {                     // cut short: its lists end inside the image
			if(*pCached != ubFrame) {
				__builtin_memcpy(pE + 2, g_pGunSpr[ubFrame][0], GUN_IMG_BYTES);
				__builtin_memcpy(pO + 2, g_pGunSpr[ubFrame][1], GUN_IMG_BYTES);
			}
			pE[2 + 2 * ubRows] = pE[3 + 2 * ubRows] = pO[2 + 2 * ubRows] = pO[3 + 2 * ubRows] = 0;
			*pCached = 0xFF;
		}
		else if(*pCached != ubFrame && ubCopies) {   // (the rest next picture: an old image for a frame)
			--ubCopies;
			__builtin_memcpy(pE + 2, g_pGunSpr[ubFrame][0], GUN_IMG_BYTES);
			__builtin_memcpy(pO + 2, g_pGunSpr[ubFrame][1], GUN_IMG_BYTES);
			*pCached = ubFrame;
		}
		pD->bob = BOB_TYPES;                  // on a sprite: not for the blitter
	}
	for(UBYTE p = 0; p < 2; ++p) {            // each list ends after its last gun
		UWORD uwOffs = (UWORD)(pSlots[p] * GUN_SLOT_WORDS);
		UWORD *pE = s_pGunList[ubBfr][p * 2] + uwOffs, *pO = s_pGunList[ubBfr][p * 2 + 1] + uwOffs;
		pE[0] = pE[1] = pO[0] = pO[1] = 0;
	}
}

// --------------------------------------------------------------- copper ---
// Rebuilt into the back list each picture (the ring's wrap line moves with
// the camera), by inline stores: about 60 commands, then an end. Every change
// sits at the start of its line (before the fetch at 0x30), so none can run
// past the end of line 255 before the copper waits for it (copw.h's rule).

#define R_BPLPT(n) (0x0E0 + 4 * (n))
#define R_SPRPT(n) (0x120 + 4 * (n))
#define R_COLOR(n) (0x180 + 2 * (n))
#define R_BPLCON0 0x100
#define R_BPLCON1 0x102
#define R_BPLCON2 0x104
#define R_BPL1MOD 0x108
#define R_BPL2MOD 0x10A
#define R_DDFSTRT 0x092
#define R_DDFSTOP 0x094
#define R_COP2LC 0x084
static UWORD *s_pHudCop[2];   // the HUD's static copper block, per buffer (hudCopperCreate)
#define R_COPJMP2 0x08A

typedef struct {
	UWORD *p;
	UWORD uwTop;            // the view's first beam line: game line 0
	UBYTE isPast255;
} tCw;

static inline void cwMove(tCw *w, UWORD uwReg, UWORD uwVal) {
	w->p[0] = uwReg;
	w->p[1] = uwVal;
	w->p += 2;
}

static inline void cwPtr(tCw *w, UWORD uwRegHi, ULONG ulAddr) {
	cwMove(w, uwRegHi, (UWORD)(ulAddr >> 16));
	cwMove(w, (UWORD)(uwRegHi + 2), (UWORD)ulAddr);
}

// WAIT for game line uwY, colour clock ubX (even)
static inline void cwWait(tCw *w, UWORD uwY, UBYTE ubX) {
	UWORD uwBeam = (UWORD)(w->uwTop + uwY);
	if(uwBeam > 0xFF && !w->isPast255) {
		w->p[0] = 0xFFDF;           // the end of line 255 first
		w->p[1] = 0xFFFE;
		w->p += 2;
		w->isPast255 = 1;
	}
	w->p[0] = (UWORD)((uwBeam << 8) | ubX | 1);
	w->p[1] = 0xFFFE;
	w->p += 2;
}

static inline void cwEnd(tCw *w) {
	w->p[0] = 0xFFFF;
	w->p[1] = 0xFFFE;
	w->p += 2;
}

// ----------------------------------------------------- the sea and dusk ---
// Each band's colours as shown: dusk falls over a theatre (a step every 90 s,
// six at most: the colours drift toward an evening mauve), and the wave
// crests (pen 1) glitter, cycling 8 shades between the sea and the crest.
// Worked out when the dusk changes, not each picture.

#define DUSK_STEP_FRAMES 4500
#define DUSK_MAX 6
static UWORD s_pBandShown[BANDS_MAX][8];
static UWORD s_pGlitter[BANDS_MAX][8];
static UBYTE s_ubDusk = 0xFF;
static UWORD s_uwDuskClock;

static UWORD colorMix(UWORD a, UWORD b, UBYTE k, UBYTE n) {
	// a toward b by k / n (n a power of two: 8 or 16)
	UBYTE ubShift = n == 16 ? 4 : 3;
	WORD r = (WORD)((a >> 8) & 15), g = (WORD)((a >> 4) & 15), bl = (WORD)(a & 15);
	r = (WORD)(r + (mulw((WORD)(((b >> 8) & 15) - r), k) >> ubShift));
	g = (WORD)(g + (mulw((WORD)(((b >> 4) & 15) - g), k) >> ubShift));
	bl = (WORD)(bl + (mulw((WORD)((b & 15) - bl), k) >> ubShift));
	return (UWORD)((r << 8) | (g << 4) | bl);
}

static void duskUpdate(void) {
	UBYTE ubDusk = 0;
	UWORD uwT = s_uwDuskClock;
	while(uwT >= DUSK_STEP_FRAMES && ubDusk < DUSK_MAX) { uwT = (UWORD)(uwT - DUSK_STEP_FRAMES); ++ubDusk; }
	if(ubDusk == s_ubDusk) return;
	s_ubDusk = ubDusk;
	for(UBYTE b = 0; b < s_sTheatre.ubBands; ++b) {
		const UWORD *pSrc = s_sTheatre.pBands[b].pColors;
		for(UBYTE i = 0; i < 8; ++i) s_pBandShown[b][i] = colorMix(pSrc[i], 0x635, ubDusk, 16);
		static const UBYTE pWave[8] = {0, 2, 4, 6, 8, 6, 4, 2};
		for(UBYTE k = 0; k < 8; ++k) s_pGlitter[b][k] = colorMix(s_pBandShown[b][0], s_pBandShown[b][1], pWave[k], 8);
	}
}

static UBYTE s_pLogoShown[2];   // the title logo is in this buffer (logoQueue)

// ------------------------------------------------------------ title logo ---
// The ROTOR RAIDER logo (art/tools/make_title_logo.py) is a 3-plane BOB in
// PF1, the theatre panning behind it. On each of its lines the copper loads
// the 7 colours that line needs (g_pTitleLogoPal): a WAIT and 7 MOVEs a line,
// written as longwords straight from the table, all in the horizontal blank.

static UBYTE s_pLogoIn[2];   // its lines are in this buffer's list, in place

// Logo line r's copper commands at pDst; returns the end
static inline ULONG *logoLine(ULONG *pDst, UBYTE r) {
	const UWORD *pPal = g_pTitleLogoPal[r];
	UWORD uwBeam = (UWORD)(s_pView->ubPosY + LOGO_Y + r);   // (< 255: no line-255 wait here)
	*pDst++ = ((ULONG)((uwBeam << 8) | 1) << 16) | 0xFFFE;
	for(UBYTE i = 0; i < TITLE_LOGO_PENS; ++i) *pDst++ = ((ULONG)R_COLOR(1 + i) << 16) | pPal[i];
	return pDst;
}

// A band's terrain colours: the sea (COLOR00) and PF2's pens (9-15)
static inline void cwBand(tCw *w, UBYTE ubBand) {
	const UWORD *pCol = s_pBandShown[ubBand];
	cwMove(w, R_COLOR(0), pCol[0]);
	cwMove(w, R_COLOR(9), s_pGlitter[ubBand][(s_sGame.frame >> 3) & 7]);
	for(UBYTE i = 2; i < 8; ++i) cwMove(w, R_COLOR(8 + i), pCol[i]);
}

// The ring's wrap: the PF2 planes back at its start, from this line
static inline void cwWrap(tCw *w, UWORD uwLine, ULONG ulAddr) {
	cwWait(w, uwLine, 0);
	cwPtr(w, R_BPLPT(1), ulAddr);
	cwPtr(w, R_BPLPT(3), ulAddr + SCROLL_PLANE_BYTES);
	cwPtr(w, R_BPLPT(5), ulAddr + 2 * SCROLL_PLANE_BYTES);
}

__attribute__((noinline)) static void copperBuild(UBYTE ubBfr) {
	const tGame *g = &s_sGame;
	tCw sW = {.p = (UWORD *)s_pView->pCopList->pBackBfr->pList, .uwTop = s_pView->ubPosY, .isPast255 = 0};
	UWORD *pFirst = sW.p;
	// sprites: the gunship on 0-3, the turrets' guns on 4-7
	for(UBYTE s = 0; s < ART_CHOPPER_PARTS; ++s) cwPtr(&sW, R_SPRPT(s), (ULONG)s_pChopShown[ubBfr][s]->Planes[0]);
	for(UBYTE s = 0; s < 4; ++s) cwPtr(&sW, R_SPRPT(GUN_CHANNEL + s), (ULONG)s_pGunList[ubBfr][s]);
	for(UBYTE i = 4; i < 7; ++i) cwMove(&sW, R_COLOR(i), s_pColors[i]);   // (the HUD changed them)
	cwPtr(&sW, R_COP2LC, (ULONG)s_pHudCop[ubBfr]);   // where the HUD's block is
	cwMove(&sW, R_BPLCON0, BPLCON0_DPF6);
	cwMove(&sW, R_BPLCON1, scrollDelayBits(g->camX));
	cwMove(&sW, R_BPLCON2, BPLCON2_RR);
	cwMove(&sW, R_DDFSTRT, DDFSTRT_SCROLL);
	cwMove(&sW, R_DDFSTOP, DDFSTOP_LORES);
	cwMove(&sW, R_BPL1MOD, FB_ROW_BYTES - FETCH_BYTES);
	cwMove(&sW, R_BPL2MOD, SCROLL_BW - FETCH_BYTES);
	const tBitMap *pFb = s_pFb[ubBfr];
	for(UBYTE p = 0; p < 3; ++p) cwPtr(&sW, R_BPLPT(2 * p), (ULONG)pFb->Planes[p] + FB_FETCH_OFFS);
	UWORD uwWrap;
	ULONG ulWrapAddr;
	ULONG ulTop = scrollTop(g->camX, g->camY, &uwWrap, &ulWrapAddr);
	cwPtr(&sW, R_BPLPT(1), ulTop);
	cwPtr(&sW, R_BPLPT(3), ulTop + SCROLL_PLANE_BYTES);
	cwPtr(&sW, R_BPLPT(5), ulTop + 2 * SCROLL_PLANE_BYTES);
	// The island bands' colours: the band at the top, then each band that
	// starts on screen (always in open sea), in line order with the wrap
	// (and on the title, the logo's lines)
	const tTheatre *pTh = &s_sTheatre;
	UBYTE b = 0;
	while(b + 1 < pTh->ubBands && pTh->pBands[b + 1].ubRow * TILE <= g->camY) ++b;
	cwBand(&sW, b);
	WORD pBandLine[BANDS_MAX];
	UBYTE ubBands = 0;
	for(++b; b < pTh->ubBands; ++b) {
		WORD wLine = (WORD)(pTh->pBands[b].ubRow * TILE - g->camY);
		if(wLine >= PLAY_H) break;
		pBandLine[ubBands++] = wLine;
	}
	UBYTE ubBand = (UBYTE)(b - ubBands);
	UBYTE isClear = uwWrap > LOGO_Y + LOGO_H && !(ubBands && pBandLine[0] <= LOGO_Y + LOGO_H);
	if(g->state == GS_TITLE && s_pLogoShown[ubBfr] && isClear) {
		// The logo's lines sit at the same place in this buffer's list every
		// picture (what comes before them has a fixed length): written once.
		ULONG *pDst = (ULONG *)sW.p;
		if(!s_pLogoIn[ubBfr]) {
			s_pLogoIn[ubBfr] = 1;
			for(UBYTE r = 0; r < LOGO_H; ++r) pDst = logoLine(pDst, r);
		}
		sW.p = (UWORD *)((ULONG *)sW.p + LOGO_H * LOGO_CMDS);
		cwWait(&sW, LOGO_Y + LOGO_H, 0);
		for(UBYTE i = 1; i < 8; ++i) cwMove(&sW, R_COLOR(i), s_pColors[i]);
	}
	else if(g->state == GS_TITLE && s_pLogoShown[ubBfr]) {
		s_pLogoIn[ubBfr] = 0;   // (the lines will be written again)
		// the logo's lines, written from the table; events before it first,
		// those inside spliced in after their line
		while(ubBands && pBandLine[0] < LOGO_Y) {
			cwWait(&sW, (UWORD)pBandLine[0], 0);
			cwBand(&sW, ubBand++);
			for(UBYTE k = 1; k < ubBands; ++k) pBandLine[k - 1] = pBandLine[k];
			--ubBands;
		}
		if(uwWrap < LOGO_Y) {
			cwWrap(&sW, uwWrap, ulWrapAddr);
			uwWrap = PLAY_H;
		}
		ULONG *pDst = (ULONG *)sW.p;
		for(UBYTE r = 0; r < LOGO_H; ++r) {
			pDst = logoLine(pDst, r);
			UWORD uwLine = (UWORD)(LOGO_Y + r);
			if(uwLine == uwWrap || (ubBands && pBandLine[0] == (WORD)uwLine)) {
				sW.p = (UWORD *)pDst;
				if(uwLine == uwWrap) {
					cwPtr(&sW, R_BPLPT(1), ulWrapAddr);
					cwPtr(&sW, R_BPLPT(3), ulWrapAddr + SCROLL_PLANE_BYTES);
					cwPtr(&sW, R_BPLPT(5), ulWrapAddr + 2 * SCROLL_PLANE_BYTES);
					uwWrap = PLAY_H;
				}
				if(ubBands && pBandLine[0] == (WORD)uwLine) {
					cwBand(&sW, ubBand++);
					for(UBYTE k = 1; k < ubBands; ++k) pBandLine[k - 1] = pBandLine[k];
					--ubBands;
				}
				pDst = (ULONG *)sW.p;
			}
		}
		sW.p = (UWORD *)pDst;
		cwWait(&sW, LOGO_Y + LOGO_H, 0);
		for(UBYTE i = 1; i < 8; ++i) cwMove(&sW, R_COLOR(i), s_pColors[i]);
	}
	UBYTE isWrapDone = uwWrap >= PLAY_H;
	for(UBYTE k = 0; k < ubBands; ++k) {
		WORD wLine = pBandLine[k];
		if(!isWrapDone && (WORD)uwWrap <= wLine) {
			cwWrap(&sW, uwWrap, ulWrapAddr);
			isWrapDone = 1;
		}
		cwWait(&sW, (UWORD)wLine, 0);
		cwBand(&sW, ubBand++);
	}
	if(!isWrapDone) cwWrap(&sW, uwWrap, ulWrapAddr);
	// the HUD: its copper block is static (hudCopperCreate): jump there at
	// the end of the play area's last line
	cwWait(&sW, PLAY_H - 1, SWITCH_WAIT_X - 4);
	cwMove(&sW, R_COPJMP2, 0);
	cwEnd(&sW);
	s_uwCopUsed = (UWORD)((sW.p - pFirst) >> 1);
}

