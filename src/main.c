// The game's own bold font (art/tools/hudfont.py): capitals, ( ) , a
// copyright sign (written '@'), the HUD compass's 8 arrows (written 'a'-'h':
// north, north-east, ... clockwise) and its bombs ('#' carried, '_' gone).
// Lines are "typed" a few letters a picture: text is slow to draw.

#include "hudfont.h"
static tAgkFont s_sFont;

static void fontInit(void) {
	agkFontInit(&s_sFont, g_pHudFont, HUD_FONT_CHARS);
}

// Show szTarget in pText, using up to *pBudget changed letters now (it's
// shared by several lines). 1: all shown.
static UBYTE textType(tAgkText *pText, char *pStage, const char *szTarget, UBYTE *pBudget) {
	UBYTE isDone = 1, isChange = 0;
	for(UBYTE c = 0; szTarget[c]; ++c) {
		if(pStage[c] != szTarget[c]) {
			if(!*pBudget) { isDone = 0; break; }   // (the rest next time)
			pStage[c] = szTarget[c];
			--*pBudget;
			isChange = 1;
		}
	}
	if(isChange) agkTextSet(pText, pStage);
	return isDone;
}

// --------------------------------------------------------------- messages ---
// Lines of text in the play area (title, theatre, warnings, the end), drawn
// into the frame buffer by the CPU after the blitter's done. A BOB's erase may
// cross them: the letters it crossed are drawn again (as in Rotor Rescue).

#define MSG_LINES 12
#define MSG_LEN 40
#define MSG_TYPE_PER_FRAME 3
// lines 0-5 in play (a theatre cleared, the end), 6-11 the title's, under its logo
#define MSG_TITLE 6
static const UBYTE s_pMsgY[MSG_LINES] = {104, 116, 136, 148, 170, 190, 152, 162, 174, 184, 196, 206};
#define MSG_Y_MIN 104
#define MSG_Y_MAX 206
_Static_assert(LOGO_Y + LOGO_H + 2 < 152, "the title's text is under the logo");
static tAgkText s_pMsg[2][MSG_LINES];
static char s_pMsgStage[2][MSG_LINES][MSG_LEN + 1];
static ULONG s_pMsgCover[2][MSG_LINES][2];  // columns (bits) this buffer's BOBs covered last time
static ULONG s_pMsgFix[2][MSG_LINES][2];    // columns an erase crossed: redraw their letters
static UBYTE s_pMsgAnyFix[2];
static UWORD s_pMsgKey[2] = {0xFFFF, 0xFFFF};
static char s_pMsgTarget[2][MSG_LINES][MSG_LEN + 1];   // what each line is to say
static UWORD s_pMsgPending[2];                          // lines still being typed (bits)
static UWORD s_pMsgText[2];                             // lines with letters on them (bits)

static void msgInit(void) {
	for(UBYTE b = 0; b < 2; ++b) {
		for(UBYTE l = 0; l < MSG_LINES; ++l) {
			agkTextInit(&s_pMsg[b][l], &s_sFont, s_pFb[b], FB_X0, s_pMsgY[l], MSG_LEN, 4, 1);
			for(UBYTE c = 0; c < MSG_LEN; ++c) s_pMsgStage[b][l][c] = ' ';
			s_pMsgStage[b][l][MSG_LEN] = 0;
		}
	}
}

static void msgCentre(char *szOut, const char *szText) {
	UBYTE ubLen = 0;
	while(szText[ubLen] && ubLen < MSG_LEN) ++ubLen;
	UBYTE ubPad = (UBYTE)((MSG_LEN - ubLen) >> 1);
	for(UBYTE i = 0; i < MSG_LEN; ++i) szOut[i] = ' ';
	for(UBYTE i = 0; i < ubLen; ++i) szOut[ubPad + i] = szText[i];
	szOut[MSG_LEN] = 0;
}

static void strCat(char *pOut, UBYTE *pN, const char *sz) {
	while(*sz && *pN < MSG_LEN) pOut[(*pN)++] = *sz++;
	pOut[*pN] = 0;
}

// The columns a BOB covers in the message lines (for the redraw after its erase)
static void msgCover(UBYTE ubBfr, WORD x, WORD y, UWORD ubW, UBYTE ubH) {
	if(!s_pMsgText[ubBfr] || y >= MSG_Y_MAX + 8 || y + ubH <= MSG_Y_MIN) return;
	WORD c0 = (WORD)(((x - FB_X0) & ~15) >> 3), c1 = (WORD)((x - FB_X0 + ubW + 15) >> 3);
	if(c0 < 0) c0 = 0;
	if(c1 > MSG_LEN - 1) c1 = MSG_LEN - 1;
	for(UBYTE l = 0; l < MSG_LINES; ++l) {
		if((s_pMsgText[ubBfr] & (1 << l)) && y < s_pMsgY[l] + 8 && y + ubH > s_pMsgY[l]) {
			for(WORD c = c0; c <= c1; ++c) s_pMsgCover[ubBfr][l][c >> 5] |= 1UL << (c & 31);
		}
	}
}

static void msgCoverBegin(UBYTE ubBfr) {
	if(!s_pMsgText[ubBfr] && !s_pMsgAnyFix[ubBfr]) return;   // no text on screen: nothing to look after
	for(UBYTE l = 0; l < MSG_LINES; ++l) {
		s_pMsgFix[ubBfr][l][0] |= s_pMsgCover[ubBfr][l][0];
		s_pMsgFix[ubBfr][l][1] |= s_pMsgCover[ubBfr][l][1];
		s_pMsgAnyFix[ubBfr] |= (s_pMsgCover[ubBfr][l][0] | s_pMsgCover[ubBfr][l][1]) != 0;
		s_pMsgCover[ubBfr][l][0] = s_pMsgCover[ubBfr][l][1] = 0;
	}
}

// The title's second page, the music's credits (sound.toml's artist/license,
// g_pSoundCredits): its own 5 s after the controls' 5 s - where that music
// plays (it didn't fit: the game's own songs, nothing to credit)
static inline UBYTE titleCreditsPage(const tGame *g) {
	return SOUND_CREDITS_COUNT && s_ubModules && ((g->frame >> 8) & 1);
}

// "MUSIC: DOG68, DOG70 BY SONGERSON" and "CC BY  MODARCHIVE.ORG" from the
// credits (one artist and licence assumed - the first's), in the font's
// capitals; szA and szB hold MSG_LEN + 1
static void creditsLines(char *szA, char *szB) {
	UBYTE n = 0;
	strCat(szA, &n, "MUSIC: ");
	for(UBYTE i = 0; i < SOUND_CREDITS_COUNT; ++i) {
		if(i) strCat(szA, &n, ", ");
		strCat(szA, &n, g_pSoundCredits[i].szTitle);
	}
	strCat(szA, &n, " BY ");
	strCat(szA, &n, g_pSoundCredits[0].szArtist);
	szA[n] = 0;
	n = 0;
	strCat(szB, &n, g_pSoundCredits[0].szLicense);
	if(g_pSoundCredits[0].szUrl[0]) {
		strCat(szB, &n, "  ");
		strCat(szB, &n, g_pSoundCredits[0].szUrl);
	}
	szB[n] = 0;
	for(char *p = szA; *p; ++p) if(*p >= 'a' && *p <= 'z') *p = (char)(*p - 32);
	for(char *p = szB; *p; ++p) if(*p >= 'a' && *p <= 'z') *p = (char)(*p - 32);
}

// What the lines say (laid out when it changes). Lines that go blank are
// cleared at once by the blitter (queued before the objects), not typed away.
__attribute__((noinline)) static void msgPrepare(UBYTE ubBfr) {
	const tGame *g = &s_sGame;
	const char *pText[MSG_LINES] = {"", "", "", "", "", "", "", "", "", "", "", ""};
	char szA[MSG_LEN + 1], szB[MSG_LEN + 1], szC[MSG_LEN + 1];
	UBYTE n;
	switch(g->state) {
		case GS_TITLE:
			pText[MSG_TITLE + 0] = "BY PAUL ROSS SEIBERT";
			pText[MSG_TITLE + 1] = "@ 2026 DESERT PALMS SOFTWARE";
			pText[MSG_TITLE + 2] = g->steer == STEER_CLASSIC ? "STEERING: CLASSIC  (LEFT/RIGHT)" : "STEERING: ARCADE  (LEFT/RIGHT)";
			pText[MSG_TITLE + 3] = g->steer == STEER_CLASSIC ? "LEFT/RIGHT TURN, UP FLIES" : "PUSH WHERE YOU WANT TO GO";
			pText[MSG_TITLE + 4] = (g->frame & 32) ? "PRESS FIRE" : "";
			pText[MSG_TITLE + 5] = "FIRE: GUN   HOLD FIRE OR B: BOMB";
			if(titleCreditsPage(g)) {             // every other few seconds: the music's credits
				creditsLines(szA, szB);
				pText[MSG_TITLE + 2] = szA;
				pText[MSG_TITLE + 3] = szB;
				pText[MSG_TITLE + 5] = "M: MUSIC ON/OFF";
			}
			break;
		case GS_CLEAR:
			pText[1] = "THEATRE CLEARED";
			pText[2] = "ALL FACTORIES DESTROYED";
			if(g->theatre + 1 < THEATRES) {
				n = 0; strCat(szA, &n, "NEXT: "); strCat(szA, &n, g_pTheatreName[g->theatre + 1]);
				pText[4] = szA;
			}
			break;
		case GS_OVER:
		case GS_VICTORY:
			pText[0] = g->state == GS_OVER ? "GAME OVER" : "ALL THEATRES CLEARED";
			if(g->state == GS_VICTORY) pText[1] = "THE IRON COMBINE IS BROKEN";
			n = 0; strCat(szB, &n, "SCORE ");
			agkTextNumber(&szB[n], g->score, 6); n = (UBYTE)(n + 6); szB[n] = 0;
			pText[2] = szB;
			n = 0; strCat(szC, &n, "RANK: "); strCat(szC, &n, logicRank(g->score));
			pText[3] = szC;
			break;
		default:
			break;
	}
	// what the lines say changes rarely: lay them out only then
	UWORD uwKey = (UWORD)(g->state << 12 | g->steer << 4 | g->theatre << 2 |
		(g->state == GS_TITLE ? ((g->frame >> 5) & 1) | (titleCreditsPage(g) << 1) : 0));
	if(uwKey == s_pMsgKey[ubBfr]) return;
	s_pMsgKey[ubBfr] = uwKey;
	for(UBYTE l = 0; l < MSG_LINES; ++l) {
		// (a line blank before and after: its target is blank already)
		if(!pText[l][0] && !((s_pMsgText[ubBfr] | s_pMsgPending[ubBfr]) & (1 << l))) continue;
		msgCentre(s_pMsgTarget[ubBfr][l], pText[l]);
		if(pText[l][0]) {
			s_pMsgPending[ubBfr] |= (UWORD)(1 << l);
			s_pMsgText[ubBfr] |= (UWORD)(1 << l);   // (letters to come)
		}
		else if(s_pMsgText[ubBfr] & (1 << l)) {
			// blank now: one blit clears the line (and its shadow row)
			tAgkBlitArea sArea = {
				.pD = s_pFb[ubBfr]->Planes[0] + s_pFbRowOffs[s_pMsgY[l]] + FB_X0 / 8,
				.uwSize = (UWORD)(((9 * FB_BPP) << 6) | (SCREEN_W / 16)),
				.wMod = (WORD)(FB_PLANE_BYTES - SCREEN_W / 8),
			};
			agkBlitClear(agkBlitqSlot(), &sArea);
			agkBlitqPush();
			// a line across the title logo (GAME OVER's, cleared when the
			// title comes back): the logo goes in again after it, this picture.
			// The state changes after this function, so in one buffer the logo
			// went in a picture before its old lines were cleared - and every
			// other picture lacked the logo's lower half
			if(s_pLogoShown[ubBfr] && s_pMsgY[l] < LOGO_Y + LOGO_H) s_pLogoShown[ubBfr] = 0;
			tAgkText *pT = &s_pMsg[ubBfr][l];
			for(UBYTE c = 0; c < MSG_LEN; ++c) s_pMsgStage[ubBfr][l][c] = pT->szShown[c] = ' ';
			s_pMsgPending[ubBfr] &= (UWORD)~(1 << l);
			s_pMsgText[ubBfr] &= (UWORD)~(1 << l);
			s_pMsgFix[ubBfr][l][0] = s_pMsgFix[ubBfr][l][1] = 0;
		}
	}
}

// Types the lines' new letters (a few a picture) and redraws the letters an
// erase crossed: after the blitter's done
__attribute__((noinline)) static void msgUpdate(UBYTE ubBfr) {
	if(!s_pMsgPending[ubBfr] && !s_pMsgAnyFix[ubBfr]) return;   // the usual case in play
	s_pMsgAnyFix[ubBfr] = 0;
	UBYTE ubBudget = MSG_TYPE_PER_FRAME;
	for(UBYTE l = 0; l < MSG_LINES; ++l) {
		char *pStage = s_pMsgStage[ubBfr][l];
		ULONG *pFix = s_pMsgFix[ubBfr][l];
		const char *szLine = s_pMsgTarget[ubBfr][l];
		UBYTE isChange = 0;
		if(s_pMsgPending[ubBfr] & (1 << l)) {
			UBYTE isDone = 1;
			for(UBYTE c = 0; c < MSG_LEN; ++c) {
				if(pStage[c] != szLine[c]) {
					if(ubBudget) {
						pStage[c] = szLine[c];
						--ubBudget;
						isChange = 1;
					}
					else isDone = 0;
				}
			}
			if(isDone) {
				s_pMsgPending[ubBfr] &= (UWORD)~(1 << l);
				UBYTE isBlank = 1;
				for(UBYTE c = 0; c < MSG_LEN; ++c) if(pStage[c] != ' ') { isBlank = 0; break; }
				if(isBlank) s_pMsgText[ubBfr] &= (UWORD)~(1 << l);
				else s_pMsgText[ubBfr] |= (UWORD)(1 << l);
			}
		}
		if((pFix[0] | pFix[1]) && (s_pMsgText[ubBfr] & (1 << l))) {
			tAgkText *pT = &s_pMsg[ubBfr][l];
			for(UBYTE c = 0; c < MSG_LEN; ++c) {
				if((pFix[c >> 5] & (1UL << (c & 31))) && pStage[c] != ' ') {
					pT->szShown[c] = 1;
					isChange = 1;
				}
			}
			pFix[0] = pFix[1] = 0;
		}
		if(isChange) agkTextSet(&s_pMsg[ubBfr][l], pStage);
	}
}

