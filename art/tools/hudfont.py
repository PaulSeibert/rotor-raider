# the order: agk's AGK_FONT8_CHARS, then the extras main.c's FONT_CHARS names
CHARS = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ!/:.-" + "(),@abcdefgh#_"


def main():
    lines = ['// Generated by art/tools/hudfont.py - don\'t edit. ROTOR RAIDER\'s font:',
             '// bold capitals, 7x7 in 8x8 cells (agk/text.h makes the shadow).',
             '#ifndef _HUDFONT_H_', '#define _HUDFONT_H_',
             '#define HUD_FONT_CHARS "%s"' % CHARS.replace('\\', '\\\\'),
             '#define HUD_FONT_COUNT %d' % len(CHARS),
             'static const unsigned char g_pHudFont[HUD_FONT_COUNT][8] = {']
    for c in CHARS:
        rows = G[c]
        assert len(rows) == 7 and all(len(r) == 7 for r in rows), c
        vals = [sum(0x80 >> x for x, ch in enumerate(r) if ch == '#') for r in rows] + [0]
        lines.append('\t{%s},   // %s' % (', '.join('0x%02X' % v for v in vals), c))
    lines += ['};', '#endif', '']
    open(OUT, 'w').write('\n'.join(lines))
    print(f'{OUT}: {len(CHARS)} characters')


if __name__ == '__main__':
    main()
